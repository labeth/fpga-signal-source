#!/usr/bin/env python3
"""gen_bits.py <can|flexray|manchester> — write <proto>.v, a fixed wire-bit
player for the Alchitry Au (100 MHz). The frames repeat forever on C1 and C2.

  can        : classic CAN 500 kbit/s, dominant low. ID 0x123 "55 AA 0F F0"
               (good), ID 0x124 same data with a corrupted CRC, ID 0x100 "11 22".
  flexray    : 10 Mbit/s, idle high. Frame ID 1 with payload "Hi U\\xAA\\x0F\\xF0\\n",
               then frame ID 2 with a corrupted CRC-24 trailer.
  manchester : 1 Mbit/s IEEE, MSB-first 16-bit words, idle high.
               Frames {1234 5678} and {A55A 0FF0}.
The outputs are driven inverted (INVERT=1, the default): this scope's front
end shows the fixture's logic levels inverted, so the decoders see the
protocol's own polarity.
"""
import os, sys

def can_crc15(bits):
    crc = 0
    for b in bits:
        nxt = ((crc >> 14) & 1) ^ b
        crc = (crc << 1) & 0x7fff
        if nxt:
            crc ^= 0x4599
    return crc

def msb(v, n):
    return [(v >> (n - 1 - k)) & 1 for k in range(n)]

def stuff(bits):
    out, run_val, run_len = [], -1, 0
    for b in bits:
        if run_len == 5:
            s = 1 - run_val
            out.append(s)
            run_val, run_len = s, 1
        out.append(b)
        if b == run_val:
            run_len += 1
        else:
            run_val, run_len = b, 1
    return out, run_val, run_len

def can_frame(ident, data, crc_xor=0):
    body = [0] + msb(ident, 11) + [0, 0, 0] + msb(len(data), 4)
    for d in data:
        body += msb(d, 8)
    crc = can_crc15(body) ^ crc_xor
    wire, rv, rl = stuff(body + msb(crc, 15))
    if rl == 5:
        wire.append(1 - rv)
    return wire + [1, 0, 1] + [1] * 10

def flex_crc11(bits):
    crc = 0x1A
    for b in bits:
        m = (crc >> 10) & 1
        crc = (crc << 1) & 0x7ff
        if m ^ b:
            crc ^= 0x385
    return crc

def flex_crc24(data):
    crc = 0xFEDCBA
    for by in data:
        for b in range(7, -1, -1):
            m = (crc >> 23) & 1
            crc = (crc << 1) & 0xffffff
            if m ^ ((by >> b) & 1):
                crc ^= 0x5D6DCB
    return crc

def flex_frame(ident, cycle, payload, trailer_xor=0):
    n = len(payload) // 2
    hdr = (ident & 0x7ff) << 24 | n << 17 | cycle & 0x3f
    hdr |= flex_crc11([0, 0] + msb(ident, 11) + msb(n, 7)) << 6
    data = [(hdr >> (8 * i)) & 0xff for i in range(4, -1, -1)] + list(payload)
    crc = flex_crc24(data) ^ trailer_xor
    data += [crc >> 16 & 0xff, crc >> 8 & 0xff, crc & 0xff]
    wire = [0] * 6 + [1]
    for by in data:
        wire += [1, 0] + msb(by, 8)
    return wire + [0, 1] + [1] * 11

def manchester(words):
    # Half-bit cells; IEEE: a one is low then high.
    cells = [1] * 16
    for w in words:
        for b in msb(w, 16):
            cells += [1 - b, b]
    return cells + [1] * 16

proto = sys.argv[1]
if proto == "can":
    wire = [1] * 20 + can_frame(0x123, [0x55, 0xAA, 0x0F, 0xF0]) + [1] * 20 + \
        can_frame(0x124, [0x55, 0xAA, 0x0F, 0xF0], crc_xor=0x10) + [1] * 20 + can_frame(0x100, [0x11, 0x22]) + [1] * 200
    clocks = 200
elif proto == "flexray":
    msg = [0x48, 0x69, 0x20, 0x55, 0xAA, 0x0F, 0xF0, 0x0A]
    wire = [1] * 20 + flex_frame(1, 0, msg) + [1] * 20 + flex_frame(2, 1, msg, trailer_xor=1) + [1] * 2000
    clocks = 10
elif proto == "manchester":
    wire = manchester([0x1234, 0x5678]) + [1] * 16 + manchester([0xA55A, 0x0FF0]) + [1] * 400
    clocks = 50
else:
    sys.exit(__doc__)
n = len(wire)
bits = "".join(str(b) for b in reversed(wire))
w = max(1, (n - 1).bit_length())
d = max(1, (clocks - 1).bit_length())
open(f"{proto}.v", "w").write(f"""// Generated by gen_bits.py {proto}: {n} wire bits, {clocks} clocks each at 100 MHz.
module sig(input wire clk,output wire c1,output wire c2);
 localparam [{n - 1}:0] WIRE={n}'b{bits};
 reg [{w - 1}:0] index=0;reg [{d - 1}:0] div=0;
 assign c1={'~' if os.environ.get('INVERT', '1') == '1' else ''}WIRE[index];assign c2=c1;
 always @(posedge clk)begin
  if(div=={clocks - 1})begin div<=0;index<=index=={n - 1}?0:index+1'b1;end
  else div<=div+1'b1;
 end
endmodule
""")
print(f"{proto}.v: {n} bits, {n * clocks / 100e6 * 1e3:.3f} ms period")
